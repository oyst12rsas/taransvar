#!/usr/bin/env python3
"""Enable Gatekeeper handoff during explicit node enrollment; never expose the agent token."""
import argparse
import grp
import hashlib
import ipaddress
import json
import os
from pathlib import Path
import re
import secrets
import subprocess
import urllib.parse

import enroll_google_manager as agent
import local_manager_policy


def callback_url(base):
    p = urllib.parse.urlsplit(base)
    if (p.scheme not in ('http', 'https') or not p.hostname or p.username or p.password
            or p.query or p.fragment or p.path not in ('', '/', '/gatekeeper', '/gatekeeper/', '/gatekeeper/google_callback.php')
            or re.search(r'[\s\\]', base)):
        raise ValueError('Use the Gatekeeper HTTP(S) base URL without credentials or query')
    if p.scheme == 'http' and ipaddress.ip_address(p.hostname) not in ipaddress.ip_network('100.64.0.0/10'):
        raise ValueError('HTTP Gatekeeper must use its NetBird overlay IPv4 address')
    if p.port is not None and not 1 <= p.port <= 65535:
        raise ValueError('Invalid port')
    return urllib.parse.urlunsplit((p.scheme, p.netloc, '/gatekeeper/google_callback.php', '', ''))


def discover_base():
    addresses = json.loads(subprocess.check_output(['/usr/sbin/ip', '-j', '-4', 'address', 'show'], text=True))
    ips = {a['local'] for dev in addresses if re.fullmatch(r'wt[0-9]+', dev['ifname'])
           for a in dev.get('addr_info', [])
           if ipaddress.ip_address(a['local']) in ipaddress.ip_network('100.64.0.0/10')}
    if len(ips) != 1:
        raise ValueError('Cannot select one NetBird address; use --gatekeeper-url')
    return 'http://' + ips.pop()


def php_config(config):
    # JSON is embedded as a quoted PHP string, not executable caller-supplied PHP.
    data = json.dumps(config).replace('\\', '\\\\').replace("'", "\\'")
    return "<?php\n// Generated by explicit Google manager enrollment. Agent token remains root-only.\nreturn json_decode('" + data + "', true, 512, JSON_THROW_ON_ERROR);\n"


def enable(base=None, web_root=Path('/var/www/html'), root=Path('/'), opener=None):
    web_root = Path(web_root)
    if not (web_root/'gatekeeper/google_callback.php').is_file():
        if base:
            raise ValueError('Gatekeeper not deployed at --web-root')
        return None
    directory = root/'etc/tarasec'
    config_path = directory/'gatekeeper-google.php'
    gid = grp.getgrnam('www-data').gr_gid
    # Only directory traversal, never listing or access to root-only agent keys.
    # Install acl before this helper; fail visibly if ACLs are unsupported.
    subprocess.run(['setfacl', '-m', 'u:www-data:--x', str(directory)], check=True)
    pending = directory/'gatekeeper-google-enrollment.json'
    if config_path.exists() and not pending.exists():
        # Preserve hand-configured clients and their separate central registration.
        if config_path.is_symlink() or config_path.stat().st_uid != 0:
            raise ValueError('Unsafe existing Gatekeeper configuration')
        print('Existing Gatekeeper Google configuration retained; directory access repaired.')
        return None
    receipt = json.loads(agent.private_read(directory/'agent-enrollment.json'))
    token = agent.private_read(directory/'agent-node.token').strip()
    digest = hashlib.sha256(token.encode()).hexdigest()
    api = receipt['approval_url']
    agent.enrollment_url(api)
    if pending.exists():
        config = json.loads(agent.private_read(pending))
        if config['agent_api'] != api or config['client_id'] != 'gk-'+digest[:24]:
            raise ValueError('Gatekeeper enrollment identity/provider changed')
    else:
        config = dict(client_id='gk-'+digest[:24], shared_secret=secrets.token_hex(32),
                      agent_api=api, sign_in_url=api.rsplit('/', 1)[0]+'/gatekeeper.php',
                      authorization='local_managers')
    url = callback_url(base or config.get('return_url') or discover_base())
    config['return_url'] = url
    # Publish local Gatekeeper grants before contacting central. Revocations must
    # remain effective locally even if the registration request subsequently fails.
    hashes = sorted(local_manager_policy.manager_hashes(str(directory/'access.conf')))
    policy = directory/'gatekeeper-managers.json'
    write_web_file(policy, json.dumps(hashes)+'\n', gid)
    agent.atomic_write(pending, json.dumps(config)+'\n')
    registration = dict(client_id=config['client_id'], return_url=url,
                        secret_hash=hashlib.sha256(config['shared_secret'].encode()).hexdigest())
    answer = agent.register(api, token, receipt['nickname'], hashes, opener, gatekeeper=registration)
    expected = dict(registration, node_id=receipt['node_id'])
    if answer.get('gatekeeper') != expected:
        raise ValueError('Central service did not confirm Gatekeeper registration; update it first')
    write_web_file(config_path, php_config(config), gid)
    return url.replace('google_callback.php', 'index.php?f=login')


def write_web_file(path, text, gid):
    if path.is_symlink():
        raise ValueError('Symlink web configuration prohibited')
    # Do not reuse the root-only agent writer: the web process needs read access.
    import tempfile
    fd, tmp = tempfile.mkstemp(dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as f:
            os.fchown(f.fileno(), 0, gid)
            os.fchmod(f.fileno(), 0o640)
            f.write(text)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp): os.unlink(tmp)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--gatekeeper-url')
    parser.add_argument('--web-root', default='/var/www/html')
    args = parser.parse_args()
    if os.geteuid() != 0: parser.error('Run as root')
    try:
        url = enable(args.gatekeeper_url, Path(args.web_root))
    except Exception:
        raise SystemExit('Gatekeeper enrollment incomplete. Check local deployment/NetBird URL, ACL support and central service version; retry the same enrollment. Credentials retained; no secrets printed.')
    if url: print('Gatekeeper Google sign-in configured: '+url)


if __name__ == '__main__': main()
